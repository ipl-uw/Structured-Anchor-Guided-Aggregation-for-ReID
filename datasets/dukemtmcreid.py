import glob
import re
import urllib
import zipfile
import os.path as osp

from utils.iotools import mkdir_if_missing
from .bases import BaseImageDataset


class DukeMTMCreID(BaseImageDataset):
    """
    DukeMTMC-reID
    Reference:
      Ristani et al. Performance Measures and a Data Set for Multi-Target, Multi-Camera Tracking. ECCVW 2016.
      Zheng et al. Unlabeled Samples Generated by GAN Improve the Person Re-id Baseline in vitro. ICCV 2017.

    Dataset statistics:
      702 train identities, 16 522 train images, 2 228 query images, 17 661 gallery images, 8 cameras.

    Accepts either:
      - direct path to the dataset root (i.e. root/bounding_box_train exists), or
      - the legacy nested layout:  root/dukemtmcreid/DukeMTMC-reID/bounding_box_train
    """
    dataset_dir = 'dukemtmcreid'

    def __init__(self, root='', verbose=True, pid_begin=0, **kwargs):
        super(DukeMTMCreID, self).__init__()
        self.dataset_url = 'http://vision.cs.duke.edu/DukeMTMC/data/misc/DukeMTMC-reID.zip'

        if osp.exists(osp.join(root, 'bounding_box_train')):
            self.dataset_dir = root
            self.train_dir   = osp.join(root, 'bounding_box_train')
            self.query_dir   = osp.join(root, 'query')
            self.gallery_dir = osp.join(root, 'bounding_box_test')
        else:
            self.dataset_dir = osp.join(root, self.dataset_dir)
            self.train_dir   = osp.join(self.dataset_dir, 'DukeMTMC-reID/bounding_box_train')
            self.query_dir   = osp.join(self.dataset_dir, 'DukeMTMC-reID/query')
            self.gallery_dir = osp.join(self.dataset_dir, 'DukeMTMC-reID/bounding_box_test')

        self.pid_begin = pid_begin
        self._download_data()
        self._check_before_run()

        train   = self._process_dir(self.train_dir,   relabel=True)
        query   = self._process_dir(self.query_dir,   relabel=False)
        gallery = self._process_dir(self.gallery_dir, relabel=False)

        if verbose:
            print("=> DukeMTMC-reID loaded")
            self.print_dataset_statistics(train, query, gallery)

        self.train   = train
        self.query   = query
        self.gallery = gallery

        self.num_train_pids, self.num_train_imgs, self.num_train_cams, self.num_train_vids = \
            self.get_imagedata_info(self.train)
        self.num_query_pids, self.num_query_imgs, self.num_query_cams, self.num_query_vids = \
            self.get_imagedata_info(self.query)
        self.num_gallery_pids, self.num_gallery_imgs, self.num_gallery_cams, self.num_gallery_vids = \
            self.get_imagedata_info(self.gallery)

    def _download_data(self):
        if osp.exists(self.dataset_dir):
            return
        mkdir_if_missing(self.dataset_dir)
        fpath = osp.join(self.dataset_dir, osp.basename(self.dataset_url))
        print("Downloading DukeMTMC-reID dataset …")
        urllib.request.urlretrieve(self.dataset_url, fpath)
        print("Extracting …")
        with zipfile.ZipFile(fpath, 'r') as z:
            z.extractall(self.dataset_dir)

    def _check_before_run(self):
        for path in (self.dataset_dir, self.train_dir, self.query_dir, self.gallery_dir):
            if not osp.exists(path):
                raise RuntimeError(f"'{path}' is not available")

    def _process_dir(self, dir_path, relabel=False):
        img_paths = glob.glob(osp.join(dir_path, '*.jpg'))
        pattern   = re.compile(r'([-\d]+)_c(\d)')

        pid_container = set()
        for img_path in img_paths:
            pid, _ = map(int, pattern.search(img_path).groups())
            pid_container.add(pid)
        pid2label = {pid: label for label, pid in enumerate(pid_container)}

        dataset = []
        for img_path in img_paths:
            pid, camid = map(int, pattern.search(img_path).groups())
            assert 1 <= camid <= 8
            camid -= 1
            if relabel:
                pid = pid2label[pid]
            dataset.append((img_path, self.pid_begin + pid, camid, 0))
        return dataset
